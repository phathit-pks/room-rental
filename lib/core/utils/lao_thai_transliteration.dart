/// Displays Lao names and text in Thai script without changing stored data.
String transliterateLaoToThai(String text) {
  if (!_laoCharacters.hasMatch(text)) return text;

  var result = text;
  for (final entry in _knownSpellings.entries) {
    result = result.replaceAll(entry.key, entry.value);
  }
  return result.replaceAllMapped(
    _laoCharacters,
    (match) => _characters[match[0]] ?? match[0]!,
  );
}

